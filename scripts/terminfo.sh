#!/bin/sh
# Regenerate internal/terminfo from the pinned Ghostty revision: the terminfo
# source Ghostty itself would install (written by its own Zig definitions), and
# the portable compiled entry that ntrecord embeds. Run after bumping
# ghostty_revision in scripts/native-common.sh; needs tic (ncurses) as well.
set -eu
root=$(CDPATH= cd -- "$(dirname -- "$0")/.." && pwd)
. "$root/scripts/native-common.sh"
need tic
sh "$root/scripts/bootstrap-tools.sh"
[ -d "$deps/ghostty-$ghostty_revision" ] || sh "$root/scripts/build-libghostty.sh"
zig="${ZIG:-$deps/tools/bin/zig}"
out="$root/internal/terminfo"
work=$(mktemp -d)
trap 'rm -rf "$work"' EXIT HUP INT TERM
"$zig" run --cache-dir "$work/cache" --global-cache-dir "$deps/zig-cache" \
    --dep terminfo -Mroot="$root/scripts/terminfo-driver.zig" \
    -Mterminfo="$deps/ghostty-$ghostty_revision/src/terminfo/main.zig" >"$work/body"
{
    printf '# Generated by scripts/terminfo.sh from Ghostty %s. Do not edit.\n' "$ghostty_revision"
    cat "$work/body"
} >"$out/xterm-ghostty.terminfo"
tic -x -o "$work/db" "$out/xterm-ghostty.terminfo" 2>/dev/null
blob=$(find "$work/db" -type f -name xterm-ghostty | head -n 1)
[ -n "$blob" ] || fail 'tic did not produce an xterm-ghostty entry.'
cp "$blob" "$out/xterm-ghostty"
printf 'Wrote %s/xterm-ghostty and xterm-ghostty.terminfo (%s bytes)\n' "$out" "$(wc -c <"$out/xterm-ghostty" | tr -d ' ')"
